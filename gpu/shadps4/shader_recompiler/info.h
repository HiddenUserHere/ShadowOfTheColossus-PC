/// sotc: SOTC_VSIZE_PROBE. Where one flattened-buffer dword came from: the SRT walker copies it from
/// path[0] (a user data SGPR index holding a 48-bit table pointer), follows path[1..] (dword offsets
/// of pointer loads) and reads the dword at table + src_off_dw. valid = false when a step is dynamic.
/// Filled by FlattenExtendedUserdataPass (host bookkeeping only, no code change). Not serialized, so an
/// Info restored from the pipeline cache has no entries.
struct SotcSrtSource {
    u32 dst_off_dw{};
    u32 src_off_dw{};
    std::vector<u32> path;
    bool valid{};
};

/// sotc: SOTC_GENERIC_BUFFERS=1 (off by default). An indexed (or thread-id indexed) access to an unswizzled
/// buffer reads the stride from its V# at run time (dword 1 bits 16..29, from the flattened user data) instead of
/// the stride of the V# seen at translation, and the stride leaves the specialization key (FillBuffer). The same
/// code then serves every stride: the key no longer depends on the struct size of each draw's buffers.
inline bool GenericBufferStride() {
    static const bool on = [] {
        const char* v = std::getenv("SOTC_GENERIC_BUFFERS");
        return v && v[0] >= '1' && v[0] <= '9';
    }();
    return on;
}

/// sotc: SOTC_GENERIC_BUFFERS=2 (implies the generic stride). An untyped formatted load (buffer_load_format_*) of a
/// read-only buffer whose V# holds one of the formats below decodes the format at run time, from V# dword 3 (data
/// and number format, dst_sel), instead of the format of the V# seen at translation; the format, swizzle and number
/// conversion then leave the specialization key (FillBuffer). Other formats keep the specialized code and key.
/// sotc: SOTC_SPV_SALT=N (diagnostic, 0 = off): every module carries the string "sotc salt N" and the shader cache
/// version moves with N, so the port's cache and the driver's own cache both miss: a cold first session on demand,
/// to measure what a player's first run costs (driver compile times in the SOTC ASYNC COMPUTE line).
inline uint32_t SpvSalt() {
    static const uint32_t salt = [] {
        const char* v = std::getenv("SOTC_SPV_SALT");
        return v ? static_cast<uint32_t>(std::strtoul(v, nullptr, 10)) % 1000u : 0u;
    }();
    return salt;
}

/// sotc: SOTC_SPV_PROGRAM_IDS=1 (diagnostic, default off): every module carries its program hash (an OpString, and the
/// first field of the SOTC_HEAP / SOTC_SHADER_ADDR verify records). Off, two programs whose translation is the same
/// code give byte-identical SPIR-V, so the driver's pipeline cache builds their pipelines once (pipeline-content
/// dedup, docs/re-stutters/native/re-pipelines/README.md step 1). The records then carry 0 as the program.
inline bool SpvProgramIds() {
    static const bool on = [] {
        const char* v = std::getenv("SOTC_SPV_PROGRAM_IDS");
        return v && v[0] == '1';
    }();
    return on;
}

/// sotc: SOTC_VS_DRAW_KIND=1 (default off): one vertex module for both draw kinds of an instanced vertex program (VGPR
/// component count 3). SotC draws them direct (user SGPR 2 is user data, no start instance) or indirect (the command
/// processor writes the start instance to user SGPR 2), and each kind was a permutation of its own. With the switch the
/// SGPR is translated as user data + BaseInstance (SwVertexRuntimeInfo::instance_sgpr_add), a direct draw has
/// BaseInstance 0, and an indirect draw sees user data 0 in that SGPR (PipelineCache bind_stage), so the two kinds
/// share the module, the pipeline and the pretranslated variant (docs/re-stutters/native/re-pipelines/README.md, 3a).
inline bool VsDrawKindOn() {
    static const bool on = [] {
        const char* v = std::getenv("SOTC_VS_DRAW_KIND");
        return v && v[0] == '1';
    }();
    return on;
}
/// The start instance SGPR of SotC's indirect draws: SPI_SHADER_USER_DATA_VS_0 (0x4c) + 2, user SGPR 2.
constexpr uint16_t kVsDrawKindInstanceSgpr = 0x4c + 2;

