inline bool GenericBufferFormat() {
    static const bool on = [] {
        const char* v = std::getenv("SOTC_GENERIC_BUFFERS");
        return v && v[0] >= '2' && v[0] <= '9';
    }();
    return on;
}

/// The (raw V# data format, raw V# number format) pairs the generic decoder handles: the game's formatted buffer
/// formats (SOTC_PREDICT_BUFFERS_OUT), with no number conversion and no swizzle remap other than the single-channel
/// alpha-to-red one (AmdGpu::RemapSwizzle).
struct GenericBufferFormatPair {
    u8 data_format;
    u8 num_format;
};
inline constexpr std::array<GenericBufferFormatPair, 17> kGenericBufferFormats{{
    // Float: 32-bit components are raw dwords, 16-bit ones are halves.
    {4, 7}, {11, 7}, {13, 7}, {14, 7}, {2, 7}, {5, 7}, {12, 7},
    // Uint.
    {1, 4}, {2, 4}, {4, 4}, {10, 4}, {11, 4}, {12, 4}, {13, 4}, {14, 4},
    // Unorm.
    {9, 0}, {10, 0},
}};
/// The key's data format of a generic formatted buffer (6 bits; no real data format uses it).
inline constexpr u32 kGenericBufferFormatKey = 63u;

inline bool IsGenericBufferFormat(u32 data_format, u32 num_format) {
    for (const auto& pair : kGenericBufferFormats) {
        if (pair.data_format == data_format && pair.num_format == num_format) {
            return true;
        }
    }
    return false;
}

/// The decision the key (FillBuffer) and the translation (resource_patching_pass.cpp, lower_buffer_format_to_raw.cpp)
/// share: it reads only the cached BufferResource and the V# of the draw. A typed load (tbuffer_load_format_*) never
/// reads the V# format, so it is right with either answer.
/// sotc: specfree (SOTC_COMPUTE_SPECFREE, a compute stage, SpecFreeStage) applies the generic decode whatever
/// SOTC_GENERIC_BUFFERS says.
inline bool GenericFormatBuffer(const BufferResource& desc, const AmdGpu::Buffer& sharp, bool specfree = false) {
    return (GenericBufferFormat() || specfree) && desc.is_formatted && !desc.is_written &&
           desc.buffer_type == BufferType::Guest && IsGenericBufferFormat(sharp.data_format, sharp.num_format);
}

/// sotc: SOTC_COMPUTE_SPECFREE=1 (default off). A compute stage's translation stops depending on the descriptor
/// fields that can be read at run time from the flattened user data (the sharp dwords are there at every dispatch):
/// buffers take their stride, swizzle (index stride, element size), add-tid bit and generic format from the V#;
/// storage images their dst_select and images their number conversion from the T#; samplers their
/// force_unnormalized and force_degamma from the S#. Those fields leave the compute specialization key (they are
/// written as fixed markers, FillBuffer / FillImage / FillSampler), so the program prebuilt at shader file load
/// (synthetic sharps, SOTC_PRETRANSLATE_COMPUTE) is the permutation its dispatches use. What stays specialized:
/// image dimension and integer type (the prebuild derives them from the instructions; the int/float combinations of
/// the ambiguous images are prebuilt, kSpecFreeMaxAmbiguous), written formatted buffers, formats the run-time decode
/// does not cover, descriptor arrays and mip fallbacks (num_bindings), fmasks. Graphics stages are untouched. The shader cache
/// version and the pipeline key version carry the switch (vk_pipeline_serialization.cpp).
inline bool ComputeSpecFree() {
    static const bool on = [] {
        const char* v = std::getenv("SOTC_COMPUTE_SPECFREE");
        return v && v[0] == '1';
    }();
    return on;
}

/// sotc: SOTC_COMPUTE_SPECFREE: the marker of a run-time number conversion in an image key (no real conversion uses it).
inline constexpr u32 kSpecFreeConversionKey = 15u;
/// sotc: SOTC_COMPUTE_SPECFREE: a compute program with up to this many type-ambiguous images (only read or written,
/// never sampled) is prebuilt in every int/float combination of them (2^k permutations, at most 8); one with more
/// gets the code's verdict and the all-flipped variant only.
inline constexpr u32 kSpecFreeMaxAmbiguous = 3u;

/// sotc: SOTC_COMPUTE_SPECFREE. True when the shader can read dword `index` of a sharp at run time: a load from the
/// flattened user data or an immediate the code built it with (an invalid fetch is always the null sharp).
template <typename T>
inline bool SpecFreeFetchReadable(const SharpFetch<T>& fetch) {
    return fetch.summary != SharpFetch<T>::Summary::Invalid;
}

/// sotc: SOTC_COMPUTE_SPECFREE. A buffer whose address math (stride, swizzle, index stride, element size, add-tid)
/// reads the V# at run time. Depends only on the cached resource, never on the V# of a dispatch.
inline bool SpecFreeBufferAddress(const BufferResource& desc) {
    return desc.buffer_type == BufferType::Guest && SpecFreeFetchReadable(desc.sharp_fetch);
}

/// sotc: SOTC_COMPUTE_SPECFREE. The data formats whose dst_select the run-time swizzle reproduces: no RemapSwizzle,
/// or the single-channel alpha-to-red one. Other formats keep the specialized swizzle (and their own permutation).
inline bool SpecFreeSwizzleFormat(u32 data_format) {
    switch (static_cast<AmdGpu::DataFormat>(data_format)) {
    case AmdGpu::DataFormat::Format1_5_5_5:
    case AmdGpu::DataFormat::Format11_11_10:
    case AmdGpu::DataFormat::Format10_10_10_2:
    case AmdGpu::DataFormat::Format4_4_4_4:
    case AmdGpu::DataFormat::Format5_6_5:
        return false;
    default:
        return true;
    }
}

/// sotc: SOTC_COMPUTE_SPECFREE. The number conversions the run-time select reproduces (None, Uint32ToUnorm,
/// UintToUscaled, SintToSscaled); the others keep the specialized conversion.
inline bool SpecFreeConversion(AmdGpu::NumberConversion conversion) {
    return conversion == AmdGpu::NumberConversion::None || conversion == AmdGpu::NumberConversion::Uint32ToUnorm ||
           conversion == AmdGpu::NumberConversion::UintToUscaled ||
           conversion == AmdGpu::NumberConversion::SintToSscaled;
}

/// sotc: SOTC_COMPUTE_SPECFREE. An image (single T#, no descriptor array) whose dst_select (storage) and number
/// conversion are read from the T# at run time. The key (FillImage) and the translation (resource_patching_pass.cpp)
/// share this decision; it reads the cached resource and the T# of the dispatch.
inline bool SpecFreeImageRuntime(const ImageResource& desc, const AmdGpu::Image& sharp) {
    return desc.array_size == 0 && SpecFreeFetchReadable(desc.sharp_fetch) &&
           SpecFreeConversion(sharp.GetNumberConversion()) &&
           (!desc.is_written || SpecFreeSwizzleFormat(static_cast<u32>(sharp.data_format)));
}

struct Info;
/// sotc: SOTC_N5_BINDLESS: the push slot of images[index] in the bindless image heap, or
/// NO_BINDLESS_IMAGE_SLOT when it keeps a classic descriptor (see the declarations at the end).
u32 BindlessImageSlotOf(const Info& info, u32 index) noexcept;

struct Info : InfoPersistent {
    struct AttributeFlags {
        bool Get(IR::Attribute attrib, u32 comp = 0) const {
            return flags[Index(attrib)] & (1 << comp);
        }

        bool GetAny(IR::Attribute attrib) const {
            return flags[Index(attrib)];
        }

        void Set(IR::Attribute attrib, u32 comp = 0) {
            flags[Index(attrib)] |= (1 << comp);
        }

        u32 NumComponents(IR::Attribute attrib) const {
            return 4;
        }

        static size_t Index(IR::Attribute attrib) {
            return static_cast<size_t>(attrib);
        }

        std::array<u8, IR::NumAttributes> flags;
    };

    enum class ReadConstType {
        None = 0,
        Immediate = 1 << 0,
        Dynamic = 1 << 1,
    };

    struct Interpolation {
        Qualifier primary;
        Qualifier auxiliary;
    };

    // sotc: runtime[slot] per thread, see g_info_slot. 0 = command processor, 1 = draw thread,
    // 2..5 reserved for draw workers.
    static constexpr u32 kInfoSlots = 6;
    std::array<InfoRuntime, kInfoSlots> runtime{};
    PersistentSrtInfo srt_info;
    /// sotc: SOTC_VSIZE_PROBE provenance of the SRT-flattened dwords (see SotcSrtSource). Empty when the
    /// switch is off or the Info came from the pipeline cache.
    std::vector<SotcSrtSource> sotc_srt_sources;
    /// sotc: SOTC_CP_SRT_PLAN=2: the guest reads of the last walker run (address, bytes), see RefreshFlatBuf
    std::vector<std::pair<u64, u32>> sotc_srt_trace;
    /// sotc: SOTC_PREDICT_PROBE step 2b. One entry per image instruction the resource pass bound: image index in
    /// images, the GCN pc of the instruction (TextureInstInfo::pc), the IR opcode and the TextureInstInfo bits.
    /// Not serialized: empty for an Info restored from the pipeline cache.
    struct SotcImageUse {
        u32 image;
        u32 pc;
        u32 opcode;
        u32 flags;
    };
    std::vector<SotcImageUse> sotc_image_uses;

    AttributeFlags loads{};
    AttributeFlags stores{};

    ReadConstType readconst_types{};
    CopyShaderData gs_copy_data;
    u32 uses_patches{};

    bool has_storage_images{};
    bool has_discard{};
    bool has_image_gather{};
    bool has_image_query{};
    bool has_flatbuf{};
    /// sotc: SOTC_PRETRANSLATE. A translation at resource load, before any draw (gpu/sotc/pretranslate.cpp): there is
    /// no user data and no guest table, so the flat buffer is zeros (RefreshFlatBuf reads no guest memory) and the
    /// resource pass writes a synthetic sharp for each resource (SotcFillSyntheticSharps). Cleared when the program is
    /// installed, so its draws refresh the flat buffer from their own user data. Not serialized.
    bool sotc_synthetic{};
    /// sotc: SOTC_PRETRANSLATE: 1 flips the integer verdict of the images the program only reads (a second
    /// pre-translation of a program whose image reads the code alone cannot tell). Not serialized.
    u8 sotc_synthetic_variant{};
    /// sotc: SOTC_PRETRANSLATE: set by the synthetic sharps when an image is only read (the verdict a variant flips).
    bool sotc_synthetic_reads{};
    /// sotc: SOTC_COMPUTE_SPECFREE: with variant 1, a nonzero mask flips only the ambiguous images whose bit is set
    /// (bit i: the i-th image only read or written, in resource order); 0 flips them all. Not serialized.
    u8 sotc_synthetic_mask{};
    /// sotc: SOTC_COMPUTE_SPECFREE: the number of those ambiguous images (set by the synthetic sharps, saturates).
    u8 sotc_synthetic_ambiguous{};
    /// sotc: implicit-LOD samples report their mip to the LOD feedback buffer (sotc_lod_stats.h)
    bool uses_lod_feedback{};
    bool uses_buffer_atomic_float_min_max{};
    bool uses_image_atomic_float_min_max{};
    bool uses_lane_id{};
    bool uses_shader_clock{};
    bool uses_group_quad{};
    bool uses_group_shuffle{};
    bool uses_group_ballot{};
    IR::Type shared_types{};
    bool uses_fp16{};
    bool uses_fp64{};
    /// sotc: the SPIR-V needs 64-bit integers (Int64 capability); see CollectShaderInfoPass.
    bool uses_int64{};
    bool uses_pack_10_11_11{};
    bool uses_unpack_10_11_11{};
    /// sotc: SOTC_SPV_FUNCS. Set by LowerBufferFormatToRaw when a generic formatted load emits
    /// UnpackGenericBufferFormat; DefineFunctions then defines the decode function. Not persistent: the emit runs
    /// right after the translation, with the same Info.
    bool uses_generic_format_decode{};
    bool uses_buffer_int64_atomics{};
    bool uses_shared_int64_atomics{};
    bool stores_tess_level_outer{};
    bool stores_tess_level_inner{};
    bool translation_failed{};
    /// sotc: SOTC_HEAP stage variant (ShaderParams::variant). Read by UsesBindlessSamplers, BindlessImageSlotOf and
    /// the heap decision, so the layout, the emitter and the host all see the same stage.
    u8 variant{StageVariantDefault};

    /// sotc: the answers of the bindless predicates above for this Info, filled by FillBindlessCache from the rules
    /// themselves. The fill runs once the Info is complete (after the translation, and after Deserialize), before
    /// anything else reads it. The cache holds the flat buffer's state of that moment: the T# of an image fixes its
    /// key, as the emitted SPIR-V does. While `ready` is false the accessors evaluate the rules instead.
    static_assert(NUM_BUFFERS <= 64, "ShaderAddrBuffer bits");
    struct BindlessCache {
        bool ready{};    // the answers below are used (accessors); false while a translation runs
        bool filled{};   // the answers of a fill are held (kept across translations of this Info)
        bool unstable{}; // sticky: permutations disagreed, so the rules are used for good
        u32 num_images{};
        u32 num_buffers{};
        bool bindless_samplers{};                  // UsesBindlessSamplers
        bool bindless_images{};                    // UsesBindlessImages
        bool heap_refused{};                       // HeapStaticRefusal
        bool heap_stage{};                         // HeapStageRule
        u64 shader_addr_buffers{};                 // bit i: buffers[i] passes the Info part of ShaderAddrBuffer
        std::array<u32, NUM_IMAGES> image_key{};   // BindlessImageKeyOf per image
        std::array<u32, NUM_IMAGES> image_slot{};  // BindlessImageSlotOf per image
    };
    BindlessCache bindless{};

    /// sotc: SOTC_BARRIER_STATIC. True when the stage writes memory: a buffer or image with is_written (stores,
    /// atomics, storage images). Set by FillBindlessCache; the draw thread reads it once per op (passes.h).
    bool writes_memory{};

    /// sotc: computes the answers from the rules and merges them into `bindless` (CombineBindlessCache). Call once
    /// the Info is complete.
    void FillBindlessCache();

    std::array<Interpolation, IR::NumParams> fs_interpolation{};

    Info() = default;
    Info(HwStage stage_, SwStage l_stage_, ShaderParams params)
        : InfoPersistent(stage_, l_stage_, params.guest_hash != 0 ? params.guest_hash : params.hash) {
        PgmBase() = params.Base();
        UserData() = params.user_data;
        variant = params.variant;
    }

    /// sotc: SOTC_HEAP. The key of this program in the caches (program cache, binaries on disk, bind cache): pgm_hash
    /// with the variant mixed in as the pipeline cache does (ShaderParams::hash), pgm_hash itself for the default.
    u64 CacheHash() const noexcept {
        return variant == StageVariantDefault ? pgm_hash : HashCombine(pgm_hash, u64{variant});
    }

    std::span<const u32>& UserData() noexcept {
        return runtime[g_info_slot].user_data;
    }
    const std::span<const u32>& UserData() const noexcept {
        return runtime[g_info_slot].user_data;
    }
    std::vector<u32>& FlatBuf() noexcept {
        return runtime[g_info_slot].flattened_ud_buf;
    }
    const std::vector<u32>& FlatBuf() const noexcept {
        return runtime[g_info_slot].flattened_ud_buf;
    }
    VAddr& PgmBase() noexcept {
        return runtime[g_info_slot].pgm_base;
    }
    VAddr PgmBase() const noexcept {
        return runtime[g_info_slot].pgm_base;
    }

    template <typename T>
    inline T ReadUdSharp(u32 sharp_idx) const noexcept {
        return *reinterpret_cast<const T*>(&FlatBuf()[sharp_idx]);
    }

    template <typename T>
    T ReadUdReg(u32 ptr_index, u32 dword_offset) const noexcept {
        T data;
        const auto& user_data = UserData();
        const u32* base = user_data.data();
        if (ptr_index != IR::NumScalarRegs) {
            std::memcpy(&base, &user_data[ptr_index], sizeof(base));
            base = reinterpret_cast<const u32*>(VAddr(base) & 0xFFFFFFFFFFFFULL);
        }
        std::memcpy(&data, base + dword_offset, sizeof(T));
        return data;
    }

    /// sotc: SOTC_BDA: the guest buffers of this shader go through the block table (BdaBlockTable).
    bool HasBdaBlockTable() const noexcept {
        for (const auto& buffer : buffers) {
            if (buffer.buffer_type == BufferType::BdaBlockTable) {
                return true;
            }
        }
        return false;
    }

    /// `bindless_samplers`: the samplers come from the heap (UsesBindlessSamplers), so they take no
    /// binding numbers. Must match what the SPIR-V emitter advances the counter by.
    void AddBindings(Backend::Bindings& bnd, bool bindless_samplers = false) const {
        bnd.buffer += buffers.size();
        bnd.unified += buffers.size() + (bindless_samplers ? 0 : samplers.size());
        for (u32 index = 0; index < images.size(); ++index) {
            // sotc: a sampled image in the bindless heap takes no binding (BindlessImageSlotOf).
            if (BindlessImageSlotOf(*this, index) != NO_BINDLESS_IMAGE_SLOT) {
                continue;
            }
            // Descriptor arrays take array_size + 1 bindings
            bnd.unified += 1 + images[index].array_size;
        }
    }

    void RefreshFlatBuf() {
        const auto& user_data = UserData();
        auto& flattened_ud_buf = FlatBuf();
        flattened_ud_buf.resize(srt_info.flattened_bufsize_dw);
        ASSERT(user_data.size() <= NUM_USER_DATA_REGS);
        if (sotc_synthetic) { // sotc: SOTC_PRETRANSLATE, no guest memory to walk
            std::fill(flattened_ud_buf.begin(), flattened_ud_buf.end(), 0u);
            return;
        }
        std::memcpy(flattened_ud_buf.data(), user_data.data(), user_data.size_bytes());
        if (srt_info.walker_func) {
            if (SrtPlanTraceEnabled()) { // sotc: SOTC_CP_SRT_PLAN=2 keeps the reads the walker makes
                SrtTraceReset();
                srt_info.walker_func(user_data.data(), flattened_ud_buf.data(), &SrtCopyWindowTraced,
                                     SrtPlanTraceContext());
                // The root pointers are read from the user data array itself: not guest memory.
                const u64 ud_begin = reinterpret_cast<uintptr_t>(user_data.data());
                SrtTraceTake(sotc_srt_trace, ud_begin, ud_begin + user_data.size_bytes());
            } else {
                srt_info.walker_func(user_data.data(), flattened_ud_buf.data(), &SrtCopyWindow,
                                     GetSrtWalkerContext());
            }
        }
        if (!sharp_tables.empty()) {
            RefreshSharpTables();
        }
    }

    /// Copies every SharpTable from guest memory into the flat buffer (zeros if unmapped)
    void RefreshSharpTables();

    /// Flat buffer dwords that hold sharp tables rather than SRT walker output
    u32 SharpTableDwords() const noexcept {
        u32 dwords = 0;
        for (const auto& table : sharp_tables) {
            dwords += table.NumDwords();
        }
        return dwords;
    }

    void ReadTessConstantBuffer(TessellationDataConstantBuffer& tess_constants) const {
        ASSERT(tess_consts_dword_offset >= 0); // We've already tracked the V# UD
        auto buf = ReadUdReg<AmdGpu::Buffer>(static_cast<u32>(tess_consts_ptr_base),
                                             static_cast<u32>(tess_consts_dword_offset));
        VAddr tess_constants_addr = buf.base_address;
        memcpy(&tess_constants,
               reinterpret_cast<TessellationDataConstantBuffer*>(tess_constants_addr),
               sizeof(tess_constants));
    }

    void Serialize(Serialization::Archive& ar) const;
    bool Deserialize(Serialization::Archive& ar);
};
