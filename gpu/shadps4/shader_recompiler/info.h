namespace Shader {

/// sotc: which copy of the per-draw shader data (InfoRuntime) this thread uses. The command
/// processor fills copy 0 when it resolves a pipeline; with SOTC_CP_THREADS the draw thread
/// (liverpool.h) binds the draw from copy 1, which it fills from what the command processor
/// captured, so the command processor can resolve the next draws meanwhile.
inline thread_local u32 g_info_slot = 0;

/// sotc: the per-draw part of Info (changes with every draw of the same shader).
struct InfoRuntime {
    std::span<const u32> user_data;
    std::vector<u32> flattened_ud_buf;
    VAddr pgm_base{};
};

enum class Qualifier : u8 {
    None,
    Smooth,
    NoPerspective,
    PerVertex,
    Flat,
    Centroid,
    Sample,
};

/**
 * Contains general information generated by the shader recompiler for an input program.
 */
struct InfoPersistent {
    BufferResourceList buffers;
    ImageResourceList images;
    SamplerResourceList samplers;
    FMaskResourceList fmasks;
    SharpTableList sharp_tables;

    u32 fetch_shader_sgpr_base{};
    u32 shared_memory_scratch_size{};

    u64 pgm_hash{};

    s32 tess_consts_dword_offset = -1;
    IR::ScalarReg tess_consts_ptr_base = IR::ScalarReg::Max;
    HwStage hw_stage;
    SwStage sw_stage;

    u8 mrt_mask{};
    bool has_fetch_shader{};
    bool has_bitwise_xor{};
    bool uses_dma{};

    InfoPersistent() = default;
    InfoPersistent(HwStage hw_stage_, SwStage sw_stage_, u64 pgm_hash_)
        : hw_stage{hw_stage_}, sw_stage{sw_stage_}, pgm_hash{pgm_hash_} {}
};

struct Info;
/// sotc: SOTC_N5_BINDLESS: the push slot of images[index] in the bindless image heap, or
/// NO_BINDLESS_IMAGE_SLOT when it keeps a classic descriptor (see the declarations at the end).
u32 BindlessImageSlotOf(const Info& info, u32 index) noexcept;

struct Info : InfoPersistent {
    struct AttributeFlags {
        bool Get(IR::Attribute attrib, u32 comp = 0) const {
            return flags[Index(attrib)] & (1 << comp);
        }

        bool GetAny(IR::Attribute attrib) const {
            return flags[Index(attrib)];
        }

        void Set(IR::Attribute attrib, u32 comp = 0) {
            flags[Index(attrib)] |= (1 << comp);
        }

        u32 NumComponents(IR::Attribute attrib) const {
            return 4;
        }

        static size_t Index(IR::Attribute attrib) {
            return static_cast<size_t>(attrib);
        }

        std::array<u8, IR::NumAttributes> flags;
    };

    enum class ReadConstType {
        None = 0,
        Immediate = 1 << 0,
        Dynamic = 1 << 1,
    };

    struct Interpolation {
        Qualifier primary;
        Qualifier auxiliary;
    };

    // sotc: runtime[slot] per thread, see g_info_slot. 0 = command processor, 1 = draw thread,
    // 2..5 reserved for draw workers.
    static constexpr u32 kInfoSlots = 6;
    std::array<InfoRuntime, kInfoSlots> runtime{};
    PersistentSrtInfo srt_info;

    AttributeFlags loads{};
    AttributeFlags stores{};

    ReadConstType readconst_types{};
    CopyShaderData gs_copy_data;
    u32 uses_patches{};

    bool has_storage_images{};
    bool has_discard{};
    bool has_image_gather{};
    bool has_image_query{};
    bool has_flatbuf{};
    /// sotc: implicit-LOD samples report their mip to the LOD feedback buffer (sotc_lod_stats.h)
    bool uses_lod_feedback{};
    bool uses_buffer_atomic_float_min_max{};
    bool uses_image_atomic_float_min_max{};
    bool uses_lane_id{};
    bool uses_shader_clock{};
    bool uses_group_quad{};
    bool uses_group_shuffle{};
    bool uses_group_ballot{};
    IR::Type shared_types{};
    bool uses_fp16{};
    bool uses_fp64{};
    /// sotc: the SPIR-V needs 64-bit integers (Int64 capability); see CollectShaderInfoPass.
    bool uses_int64{};
    bool uses_pack_10_11_11{};
    bool uses_unpack_10_11_11{};
    bool uses_buffer_int64_atomics{};
    bool uses_shared_int64_atomics{};
    bool stores_tess_level_outer{};
    bool stores_tess_level_inner{};
    bool translation_failed{};
    /// sotc: SOTC_HEAP stage variant (ShaderParams::variant). Read by UsesBindlessSamplers, BindlessImageSlotOf and
    /// the heap decision, so the layout, the emitter and the host all see the same stage.
    u8 variant{StageVariantDefault};

    /// sotc: the answers of the bindless predicates above for this Info, filled by FillBindlessCache from the rules
    /// themselves. The fill runs once the Info is complete (after the translation, and after Deserialize), before
    /// anything else reads it. The cache holds the flat buffer's state of that moment: the T# of an image fixes its
    /// key, as the emitted SPIR-V does. While `ready` is false the accessors evaluate the rules instead.
    static_assert(NUM_BUFFERS <= 64, "ShaderAddrBuffer bits");
    struct BindlessCache {
        bool ready{};    // the answers below are used (accessors); false while a translation runs
        bool filled{};   // the answers of a fill are held (kept across translations of this Info)
        bool unstable{}; // sticky: permutations disagreed, so the rules are used for good
        u32 num_images{};
        u32 num_buffers{};
        bool bindless_samplers{};                  // UsesBindlessSamplers
        bool bindless_images{};                    // UsesBindlessImages
        bool heap_refused{};                       // HeapStaticRefusal
        bool heap_stage{};                         // HeapStageRule
        u64 shader_addr_buffers{};                 // bit i: buffers[i] passes the Info part of ShaderAddrBuffer
        std::array<u32, NUM_IMAGES> image_key{};   // BindlessImageKeyOf per image
        std::array<u32, NUM_IMAGES> image_slot{};  // BindlessImageSlotOf per image
    };
    BindlessCache bindless{};

    /// sotc: SOTC_BARRIER_STATIC. True when the stage writes memory: a buffer or image with is_written (stores,
    /// atomics, storage images). Set by FillBindlessCache; the draw thread reads it once per op (passes.h).
    bool writes_memory{};

    /// sotc: computes the answers from the rules and merges them into `bindless` (CombineBindlessCache). Call once
    /// the Info is complete.
    void FillBindlessCache();

    std::array<Interpolation, IR::NumParams> fs_interpolation{};

    Info() = default;
    Info(HwStage stage_, SwStage l_stage_, ShaderParams params)
        : InfoPersistent(stage_, l_stage_, params.guest_hash != 0 ? params.guest_hash : params.hash) {
        PgmBase() = params.Base();
        UserData() = params.user_data;
        variant = params.variant;
    }

    /// sotc: SOTC_HEAP. The key of this program in the caches (program cache, binaries on disk, bind cache): pgm_hash
    /// with the variant mixed in as the pipeline cache does (ShaderParams::hash), pgm_hash itself for the default.
    u64 CacheHash() const noexcept {
        return variant == StageVariantDefault ? pgm_hash : HashCombine(pgm_hash, u64{variant});
    }

    std::span<const u32>& UserData() noexcept {
        return runtime[g_info_slot].user_data;
    }
    const std::span<const u32>& UserData() const noexcept {
        return runtime[g_info_slot].user_data;
    }
    std::vector<u32>& FlatBuf() noexcept {
        return runtime[g_info_slot].flattened_ud_buf;
    }
    const std::vector<u32>& FlatBuf() const noexcept {
        return runtime[g_info_slot].flattened_ud_buf;
    }
    VAddr& PgmBase() noexcept {
        return runtime[g_info_slot].pgm_base;
    }
    VAddr PgmBase() const noexcept {
        return runtime[g_info_slot].pgm_base;
    }

    template <typename T>
    inline T ReadUdSharp(u32 sharp_idx) const noexcept {
        return *reinterpret_cast<const T*>(&FlatBuf()[sharp_idx]);
    }

    template <typename T>
    T ReadUdReg(u32 ptr_index, u32 dword_offset) const noexcept {
        T data;
        const auto& user_data = UserData();
        const u32* base = user_data.data();
        if (ptr_index != IR::NumScalarRegs) {
            std::memcpy(&base, &user_data[ptr_index], sizeof(base));
            base = reinterpret_cast<const u32*>(VAddr(base) & 0xFFFFFFFFFFFFULL);
        }
        std::memcpy(&data, base + dword_offset, sizeof(T));
        return data;
    }

    /// sotc: SOTC_BDA: the guest buffers of this shader go through the block table (BdaBlockTable).
    bool HasBdaBlockTable() const noexcept {
        for (const auto& buffer : buffers) {
            if (buffer.buffer_type == BufferType::BdaBlockTable) {
                return true;
            }
        }
        return false;
    }

    /// `bindless_samplers`: the samplers come from the heap (UsesBindlessSamplers), so they take no
    /// binding numbers. Must match what the SPIR-V emitter advances the counter by.
    void AddBindings(Backend::Bindings& bnd, bool bindless_samplers = false) const {
        bnd.buffer += buffers.size();
        bnd.unified += buffers.size() + (bindless_samplers ? 0 : samplers.size());
        for (u32 index = 0; index < images.size(); ++index) {
            // sotc: a sampled image in the bindless heap takes no binding (BindlessImageSlotOf).
            if (BindlessImageSlotOf(*this, index) != NO_BINDLESS_IMAGE_SLOT) {
                continue;
            }
            // Descriptor arrays take array_size + 1 bindings
            bnd.unified += 1 + images[index].array_size;
        }
    }

    void RefreshFlatBuf() {
        const auto& user_data = UserData();
        auto& flattened_ud_buf = FlatBuf();
        flattened_ud_buf.resize(srt_info.flattened_bufsize_dw);
        ASSERT(user_data.size() <= NUM_USER_DATA_REGS);
        std::memcpy(flattened_ud_buf.data(), user_data.data(), user_data.size_bytes());
        if (srt_info.walker_func) {
            srt_info.walker_func(user_data.data(), flattened_ud_buf.data(), &SrtCopyWindow,
                                 GetSrtWalkerContext());
        }
        if (!sharp_tables.empty()) {
            RefreshSharpTables();
        }
    }

    /// Copies every SharpTable from guest memory into the flat buffer (zeros if unmapped)
    void RefreshSharpTables();

    /// Flat buffer dwords that hold sharp tables rather than SRT walker output
    u32 SharpTableDwords() const noexcept {
        u32 dwords = 0;
        for (const auto& table : sharp_tables) {
            dwords += table.NumDwords();
        }
        return dwords;
    }

    void ReadTessConstantBuffer(TessellationDataConstantBuffer& tess_constants) const {
        ASSERT(tess_consts_dword_offset >= 0); // We've already tracked the V# UD
        auto buf = ReadUdReg<AmdGpu::Buffer>(static_cast<u32>(tess_consts_ptr_base),
                                             static_cast<u32>(tess_consts_dword_offset));
        VAddr tess_constants_addr = buf.base_address;
        memcpy(&tess_constants,
               reinterpret_cast<TessellationDataConstantBuffer*>(tess_constants_addr),
               sizeof(tess_constants));
    }

    void Serialize(Serialization::Archive& ar) const;
    bool Deserialize(Serialization::Archive& ar);
};
DECLARE_ENUM_FLAG_OPERATORS(Info::ReadConstType);

/// sotc: merges the answers of a permutation (`fresh`, filled from its own Info) into those of its program (`stored`).
/// The first answers are kept. Equal answers keep the cache ready. Different ones (or a permutation without
/// answers) make `stored` unstable for good: the accessors then use the rules, as a permutation chosen per draw can
/// have other keys.
void CombineBindlessCache(Info::BindlessCache& stored, const Info::BindlessCache& fresh);

/// Per-game dynamic_tsharp_array_size, clamped to 64 elements (0 = off)
u32 DynamicTsharpArraySize();

/// sotc: fragment shaders measure the mip their streamed textures are sampled at, as the
/// hardware's LOD counters do (sotc_lod_stats.h). SOTC_LOD_FEEDBACK=1 turns it on.
bool LodFeedbackEnabled();

/// sotc: SOTC_STAGE_BINDINGS=1 gives each graphics stage its own descriptor set
/// (Profile::stage_bindings).
bool StageBindingsEnabled();

/// sotc: true when the samplers of this stage come from the bindless heap: SOTC_BINDLESS_SAMP is
/// on (BindlessSamplersEnabled) and the stage's samplers fit its slots (GetBindlessSamplerRange).
/// Shared by the pipeline layout and the SPIR-V emitter, so both agree on the descriptors.
bool UsesBindlessSamplers(const Info& info);

/// sotc: SOTC_N5_BINDLESS: the heap key of an image: 0..2 for float sampled (2D, 2D array, 3D),
/// 3..5 for uint sampled (the same shapes), 6..8 and 9..11 for the same shapes as non-atomic
/// storage images (read/write). NO_BINDLESS_IMAGE_KEY when the image keeps a descriptor (atomic,
/// descriptor array, mip fallback, msaa, sint). Cube is a 2D array (shape 1).
/// The emitter types the heap array with this key, the host writes the view into it.
u32 BindlessImageKeyOf(const Info& info, const ImageResource& image) noexcept;

/// sotc: BindlessImageKeyOf of info.images[index]: the cached key once the Info is complete (FillBindlessCache),
/// the rule otherwise. Per draw callers use this one.
u32 BindlessImageKeyAt(const Info& info, u32 index) noexcept;

/// sotc: true when any image of the stage is in the bindless heap (BindlessImageSlotOf).
bool UsesBindlessImages(const Info& info) noexcept;

/// sotc: SOTC_HEAP. The static rules of a heap stage, decided from the stage alone (its shader and the process
/// switches): true when the stage cannot be a heap stage (fmasks, too many images or samplers, storage or array
/// images, mip fallbacks, images without a heap key, samplers that are not in the sampler heap). A heap stage that
/// passes these answers every T#/S# through the index table (SotcArch::TableMemo), null slots included.
bool HeapStaticRefusal(const Info& info) noexcept;

/// sotc: the heap stage rule without the profile's switches (Backend::SPIRV::UsesHeapImages applies those): the variant,
/// the images and samplers the heap takes, and the static refusal. The answer is cached in Info::bindless.
bool HeapStageRule(const Info& info) noexcept;

} // namespace Shader
