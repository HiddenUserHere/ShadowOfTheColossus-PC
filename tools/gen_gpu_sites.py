# sotc: generates gpu/sotc/gpu_sites_default.inc from the SOTC_ALLOC_SITES registry table (user/alloc_sites.tsv).
#
# Usage: python tools/gen_gpu_sites.py [input.tsv] [output.inc]
#   defaults: user/alloc_sites.tsv (relative to the repository root) -> gpu/sotc/gpu_sites_default.inc
#
# Selection: rows with write_own > 0 or write_foreign > 0 (the GPU_WRITTEN / GPU_WRITTEN_MIXED sites),
# minus the render-target pool (slot 20, carved by the engine) and the render-target allocator family
# (caller1 in RT_ALLOCATOR_CALLERS). Output rows are sorted by (slot, c1, c2, c3) for stable diffs.
#
# The output holds eboot code offsets (return addresses) and heap slot numbers only; no game bytes.
import csv
import os
import sys

# Ring / per-frame heap slots (RenderSingleFrame GPU and CPU). Bit 0 of FLAGS is set for these slots.
RING_SLOTS = (
    15,  # RenderSingleFrame GPU ring
    17,  # RenderSingleFrame CPU ring
)
FLAG_RING = 1

# Render-target pool: slot 20 is carved by the engine and is never selected.
RT_POOL_SLOT = 20
# caller1 return addresses inside the render-target allocator family (never selected).
RT_ALLOCATOR_CALLERS = (0x97ec4, 0x97f10, 0x98100, 0x98320)

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DEFAULT_IN = os.path.join(ROOT, "user", "alloc_sites.tsv")
DEFAULT_OUT = os.path.join(ROOT, "gpu", "sotc", "gpu_sites_default.inc")


def parse_int(text):
    return int(text.strip(), 0)


def main(argv):
    src = argv[1] if len(argv) > 1 else DEFAULT_IN
    dst = argv[2] if len(argv) > 2 else DEFAULT_OUT

    with open(src, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))

    selected = {}
    total = len(rows)
    for r in rows:
        if int(r["write_own"]) <= 0 and int(r["write_foreign"]) <= 0:
            continue
        slot = parse_int(r["slot"])
        if slot == RT_POOL_SLOT:
            continue
        c1 = parse_int(r["caller1"])
        if c1 in RT_ALLOCATOR_CALLERS:
            continue
        c2 = parse_int(r["caller2"])
        c3 = parse_int(r["caller3"])
        key = (c1, c2, c3, slot)
        if key in selected:
            continue  # the registry keys sites the same way; a duplicate row is a re-read, keep the first
        flags = FLAG_RING if slot in RING_SLOTS else 0
        selected[key] = flags

    ordered = sorted(selected.items(), key=lambda kv: (kv[0][3], kv[0][0], kv[0][1], kv[0][2]))
    ring = sum(1 for (_, flags) in ordered if flags & FLAG_RING)

    lines = [
        "// Generated by tools/gen_gpu_sites.py from %s. Do not edit by hand." % os.path.relpath(src, ROOT).replace(os.sep, "/"),
        "// Rows: {caller1, caller2, caller3, slot, flags}. caller1..3 are eboot image offsets (return addresses,",
        "// 0xffffffffffffffff = none); slot is the engine heap slot; flags bit0 = per-frame ring heap (slots %s)." % ", ".join(str(s) for s in RING_SLOTS),
        "// Selection: write_own > 0 or write_foreign > 0, excluding slot %d and caller1 in the RT allocator family." % RT_POOL_SLOT,
        "// Input rows: %d. Selected sites: %d (ring: %d)." % (total, len(ordered), ring),
    ]
    for (c1, c2, c3, slot), flags in ordered:
        lines.append("{0x%x, 0x%x, 0x%x, %d, %d}," % (c1, c2, c3, slot, flags))

    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    print("input rows %d, selected %d (ring %d) -> %s" % (total, len(ordered), ring, dst))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
